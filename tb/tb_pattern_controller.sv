//============================================================
// Testbench: Pattern Controller
//
// Tests March mSR+ operation decoding.
//
// Verifies:
// S0  -> w0
// S1  -> w1
// S2  -> r1, w0
// S3  -> r0
// S4  -> r0
// S5  -> r0, w1
// S6  -> r1, w1
// S7  -> r1, w0, w1
// S8  -> r1, w0
// S9  -> r0, w1
// S10 -> r1
// S11 -> r1
// S12 -> r1, w0, r0
//============================================================

`timescale 1ns/1ps

module tb_pattern_controller;

    //--------------------------------------------------------
    // Parameters
    //--------------------------------------------------------
    parameter DATA_WIDTH = 8;

    //--------------------------------------------------------
    // Testbench signals
    //--------------------------------------------------------
    logic [3:0] march_step;
    logic [1:0] operation_index;

    logic                     mem_read;
    logic                     mem_write;
    logic [DATA_WIDTH-1:0]    write_data;
    logic [DATA_WIDTH-1:0]    expected_data;


    //--------------------------------------------------------
    // DUT
    //--------------------------------------------------------
    pattern_controller #(
        .DATA_WIDTH(DATA_WIDTH)
    ) dut (
        .march_step      (march_step),
        .operation_index (operation_index),

        .mem_read        (mem_read),
        .mem_write       (mem_write),
        .write_data      (write_data),
        .expected_data   (expected_data)
    );


    //--------------------------------------------------------
    // Test procedure
    //--------------------------------------------------------
    initial begin

        //----------------------------------------------------
        // Initial values
        //----------------------------------------------------
        march_step      = 4'd0;
        operation_index = 2'd0;

        #10;


        //----------------------------------------------------
        // S0 : w0
        //----------------------------------------------------
        march_step      = 4'd0;
        operation_index = 2'd0;

        #10;


        //----------------------------------------------------
        // S1 : w1
        //----------------------------------------------------
        march_step      = 4'd1;
        operation_index = 2'd0;

        #10;


        //----------------------------------------------------
        // S2 : r1, w0
        //----------------------------------------------------
        march_step      = 4'd2;

        operation_index = 2'd0;   // r1
        #10;

        operation_index = 2'd1;   // w0
        #10;


        //----------------------------------------------------
        // S3 : r0
        //----------------------------------------------------
        march_step      = 4'd3;
        operation_index = 2'd0;

        #10;


        //----------------------------------------------------
        // S4 : r0
        //----------------------------------------------------
        march_step      = 4'd4;
        operation_index = 2'd0;

        #10;


        //----------------------------------------------------
        // S5 : r0, w1
        //----------------------------------------------------
        march_step      = 4'd5;

        operation_index = 2'd0;   // r0
        #10;

        operation_index = 2'd1;   // w1
        #10;


        //----------------------------------------------------
        // S6 : r1, w1
        //----------------------------------------------------
        march_step      = 4'd6;

        operation_index = 2'd0;   // r1
        #10;

        operation_index = 2'd1;   // w1
        #10;


        //----------------------------------------------------
        // S7 : r1, w0, w1
        //----------------------------------------------------
        march_step      = 4'd7;

        operation_index = 2'd0;   // r1
        #10;

        operation_index = 2'd1;   // w0
        #10;

        operation_index = 2'd2;   // w1
        #10;


        //----------------------------------------------------
        // S8 : r1, w0
        //----------------------------------------------------
        march_step      = 4'd8;

        operation_index = 2'd0;   // r1
        #10;

        operation_index = 2'd1;   // w0
        #10;


        //----------------------------------------------------
        // S9 : r0, w1
        //----------------------------------------------------
        march_step      = 4'd9;

        operation_index = 2'd0;   // r0
        #10;

        operation_index = 2'd1;   // w1
        #10;


        //----------------------------------------------------
        // S10 : r1
        //----------------------------------------------------
        march_step      = 4'd10;
        operation_index = 2'd0;

        #10;


        //----------------------------------------------------
        // S11 : r1
        //----------------------------------------------------
        march_step      = 4'd11;
        operation_index = 2'd0;

        #10;


        //----------------------------------------------------
        // S12 : r1, w0, r0
        //----------------------------------------------------
        march_step      = 4'd12;

        operation_index = 2'd0;   // r1
        #10;

        operation_index = 2'd1;   // w0
        #10;

        operation_index = 2'd2;   // r0
        #10;


        //----------------------------------------------------
        // Finish
        //----------------------------------------------------
        $display("==============================================");
        $display("PATTERN CONTROLLER TEST COMPLETED");
        $display("==============================================");

        $finish;

    end


    //--------------------------------------------------------
    // Monitor outputs
    //--------------------------------------------------------
initial begin
    $monitor(
        "TIME=%0t | STEP=%0d | OP=%0d | READ=%b | WRITE=%b | WRITE_DATA=%h | EXPECTED=%h",
        $time,
        march_step,
        operation_index,
        mem_read,
        mem_write,
        write_data,
        expected_data
    );
end
endmodule